    public static bool TryGet(string path, out byte[]? data)
    {
        string clean = path.TrimStart('/', '\\').Replace('\\', '/');
        if (clean.Equals("l13", StringComparison.OrdinalIgnoreCase))
        {
            data = Level13Data;
            return true;
        }
        data = null;
        return false;
    }

    public static Stream? TryOpen(string path)
    {
        if (TryGet(path, out byte[]? data) && data != null)
        {
            return new MemoryStream(data, writable: false);
        }
        return null;
    }
